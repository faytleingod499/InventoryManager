#!/bin/bash
# Builds tests/stubs/playerdata.gd and tests/stubs/item_resource.gd from the decompiled game, so the tests run the game's
# own item code (add/remove/lock/cosmetic functions). Nothing from the game is stored in this repo.
#   GAME=/path/to/decompiled/webfishing ./tests/make_stubs.sh
set -e
cd "$(dirname "$0")"
GAME=${GAME:-/home/claude/wf-game/decomp}
G=$GAME/Scenes/Singletons/playerdata.gd
[ -f "$G" ] || { echo "decompiled game not found at $GAME (set GAME=...)"; exit 1; }
cp "$GAME/Resources/Scripts/item_resource.gd" stubs/item_resource.gd
# the functions are found by name, so this keeps working if the line numbers move
fn() { awk -v name="$1" '$0 ~ "^func "name"\\(" {p=1} p && /^func / && $0 !~ "^func "name"\\(" {p=0} p' "$G"; }
{
cat <<'HEAD'
extends Node
# TEST STUB (generated by make_stubs.sh): the header is hand written; the functions below are copied from the game's
# playerdata.gd except that other singletons are written get_node("/root/...") and PlayerData. is written self.
enum ITEM_QUALITIES{NORMAL, SHINING, GLISTENING, OPULENT, RADIANT, ALPHA}
const QUALITY_DATA = {0: {}, 1: {}, 2: {}, 3: {}, 4: {}, 5: {}}
const FALLBACK_ITEM = {"id": "empty_hand", "ref": 0, "size": 1.0, "quality": ITEM_QUALITIES.NORMAL, "tags": []}
var inventory = []
var locked_refs = []
var hotbar = {0: 0, 1: 0, 2: 0, 3: 0, 4: 0}
var money = 30 setget _set_cash
var cosmetics_unlocked = []
var new_cosmetics = []
var cosmetic_reset_lock = false
var notifications = []   # test only: every notification sent
signal _inventory_refresh
signal _hotbar_refresh
signal _notif_send(text, type)
signal _item_removal(ref)
signal _play_sfx(id)
HEAD
for f in _add_item _validate_item_safety _remove_item _lock_item _find_item_code _unlock_cosmetic _get_unowned_cosmetic _send_notification _set_cash; do
  fn $f
  echo
done
cat <<'TAIL'
func _record_notif(text, type): notifications.append([text, type])
func _ready(): connect("_notif_send", self, "_record_notif")
TAIL
} | sed 's#Globals\.#get_node("/root/Globals").#g; s#PlayerData\.#self.#g; s#Network\.#get_node("/root/Network").#g' > stubs/playerdata.gd
echo "stubs written ($(grep -c '^func ' stubs/playerdata.gd) functions)"
